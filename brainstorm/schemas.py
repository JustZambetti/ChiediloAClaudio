"""
Canonical data schemas for the brainstorming pipeline.

Every agent consumes and/or produces one of these documents.
They are the structured handoff contracts between agents — the
context engineering backbone of the pipeline.
"""

from __future__ import annotations
from typing import Optional
from pydantic import BaseModel, Field


# ---------------------------------------------------------------------------
# Agent 1 → all downstream agents
# ---------------------------------------------------------------------------

class IdeaDocument(BaseModel):
    """
    The canonical representation of the user's idea.
    Produced by the Harvester after a structured interview.
    Every downstream agent receives this as its base context.
    """
    version: int = Field(default=1, description="Incremented on each confirmed update")
    core_concept: str = Field(description="One-sentence essence of the idea")
    problem_solved: str = Field(description="The specific problem or gap this addresses")
    target_audience: str = Field(description="Who this is for")
    inspiration_source: Optional[str] = Field(
        default=None, description="What sparked the idea"
    )
    constraints: list[str] = Field(
        default_factory=list,
        description="Hard limits the user is not willing to change"
    )
    unknowns: list[str] = Field(
        default_factory=list,
        description="Things the user doesn't know yet but needs to figure out"
    )
    excitement_level: int = Field(
        ge=1, le=10, description="User's self-reported excitement (1-10)"
    )
    domain_tags: list[str] = Field(
        default_factory=list,
        description="Relevant domains (e.g. 'education', 'fintech', 'hardware')"
    )
    raw_quotes: list[str] = Field(
        default_factory=list,
        description="Verbatim phrases from the user worth preserving"
    )


# ---------------------------------------------------------------------------
# Agent 2 → Agent 4 (Expander)
# ---------------------------------------------------------------------------

class CritiqueDocument(BaseModel):
    """
    Produced by the Critic agent.
    Stress-tests the idea so the Expander can build on weaknesses.
    """
    round: int = Field(description="Which divergence round this critique belongs to")
    strengths: list[str] = Field(description="What genuinely works")
    weaknesses: list[str] = Field(description="Specific weak points or gaps")
    assumptions_challenged: list[str] = Field(
        description="Core assumptions and why they might be wrong"
    )
    risks: list[str] = Field(description="What could kill this idea")
    open_questions: list[str] = Field(
        description="Questions the idea leaves unanswered"
    )
    feasibility_scores: dict[str, float] = Field(
        default_factory=dict,
        description="Axes: technical, financial, social, timing (0.0–1.0 each)"
    )


# ---------------------------------------------------------------------------
# Agent 3 → Agent 4 (Expander)
# ---------------------------------------------------------------------------

class ResearchFinding(BaseModel):
    title: str
    summary: str
    source_query: str
    relevance: str = Field(description="Why this matters for the idea")


class ResearchDocument(BaseModel):
    """
    Produced by the Researcher agent via web search.
    """
    round: int
    existing_solutions: list[ResearchFinding] = Field(
        description="Direct competitors or partial solutions"
    )
    market_context: str = Field(
        description="Size, maturity, key players in this space"
    )
    adjacent_ideas: list[ResearchFinding] = Field(
        description="Ideas from other domains that solved similar problems"
    )
    trend_signals: list[str] = Field(
        description="Whether this space is heating up or cooling down"
    )
    key_data_points: list[str] = Field(
        description="Concrete numbers or facts that are relevant"
    )


# ---------------------------------------------------------------------------
# Agent 4 output → Judge + Synthesizer
# ---------------------------------------------------------------------------

class IdeaVariant(BaseModel):
    """A single idea generated by the Expander."""
    id: str = Field(description="Short unique identifier, e.g. 'v2-scamper-eliminate'")
    title: str
    description: str = Field(description="2-3 sentence explanation")
    technique_used: str = Field(
        description="Which creativity technique produced this (SCAMPER verb, analogy domain, etc.)"
    )
    diverges_from_original_by: str = Field(
        description="What's fundamentally different from the original IdeaDocument"
    )
    addresses_critique: Optional[str] = Field(
        default=None,
        description="Which specific weakness from the Critic this resolves"
    )
    inspired_by_research: Optional[str] = Field(
        default=None,
        description="Which research finding shaped this variant"
    )


class IdeaSet(BaseModel):
    """
    Produced by the Expander each round.
    Contains all idea variants generated in that round.
    """
    round: int
    directive_received: str = Field(
        description="The Judge's directive that shaped this round's expansion"
    )
    variants: list[IdeaVariant]


# ---------------------------------------------------------------------------
# Agent 5 (Judge) — loop controller
# ---------------------------------------------------------------------------

class JudgeVerdict(BaseModel):
    """
    Produced by the Judge after evaluating each round's IdeaSet.
    Controls whether the divergence loop continues.
    """
    round: int
    novelty_score: float = Field(
        ge=0.0, le=1.0,
        description="How different are these ideas from previous rounds?"
    )
    diversity_score: float = Field(
        ge=0.0, le=1.0,
        description="How different are the variants from each other within this round?"
    )
    quality_score: float = Field(
        ge=0.0, le=1.0,
        description="Composite of feasibility + originality"
    )
    similarity_to_previous: float = Field(
        ge=0.0, le=1.0,
        description="Semantic overlap with last round (high = spinning in place)"
    )
    should_continue: bool = Field(
        description="True = run another divergence round, False = converge"
    )
    stop_reason: Optional[str] = Field(
        default=None,
        description="Why we're stopping (only set when should_continue=False)"
    )
    breakout_idea_id: Optional[str] = Field(
        default=None,
        description="ID of a variant that dramatically outscores everything else"
    )
    directive: str = Field(
        description="Instruction for the next Expander round (e.g. 'go weirder', 'focus on timing constraints')"
    )
    top_variant_ids: list[str] = Field(
        description="IDs of the best variants to carry forward"
    )


# ---------------------------------------------------------------------------
# Synthesizer → final output
# ---------------------------------------------------------------------------

class Direction(BaseModel):
    """A top-level direction emerging from the full brainstorm."""
    title: str
    description: str = Field(description="2-3 sentence pitch")
    emerged_in_round: int = Field(description="Which iteration produced the seed idea")
    variant_ids: list[str] = Field(description="IDs of variants that converged here")
    open_questions: list[str] = Field(description="Must-answer questions before pursuing")
    suggested_experiment: str = Field(description="Simplest concrete first step")
    risks: list[str]
    excitement_score: float = Field(ge=0.0, le=1.0)


class BrainstormReport(BaseModel):
    """
    Final output of the pipeline. Produced by the Synthesizer.
    """
    idea_title: str = Field(description="Synthesizer's name for the overall idea space")
    total_rounds: int
    top_directions: list[Direction] = Field(description="3-5 strongest directions")
    evolution_summary: str = Field(
        description="Narrative of how the idea evolved across rounds"
    )
    what_surprised_us: list[str] = Field(
        description="Unexpected findings from research or critique"
    )
    convergence_point: Optional[str] = Field(
        default=None,
        description="If one direction clearly dominates, state it here"
    )
    next_steps: list[str] = Field(description="Prioritized action items")

    def to_markdown(self) -> str:
        lines = [
            f"# {self.idea_title}",
            f"*{self.total_rounds} divergence rounds*",
            "",
            "## Evolution",
            self.evolution_summary,
            "",
        ]
        if self.convergence_point:
            lines += [f"> **Convergence:** {self.convergence_point}", ""]

        lines += ["## Top Directions", ""]
        for i, d in enumerate(self.top_directions, 1):
            lines += [
                f"### {i}. {d.title}",
                d.description,
                f"- **Emerged:** Round {d.emerged_in_round}",
                f"- **Excitement:** {d.excitement_score:.0%}",
                f"- **First experiment:** {d.suggested_experiment}",
                "- **Risks:** " + ", ".join(d.risks),
                "- **Open questions:**",
            ]
            for q in d.open_questions:
                lines.append(f"  - {q}")
            lines.append("")

        lines += ["## What Surprised Us", ""]
        for s in self.what_surprised_us:
            lines.append(f"- {s}")

        lines += ["", "## Next Steps", ""]
        for i, step in enumerate(self.next_steps, 1):
            lines.append(f"{i}. {step}")

        return "\n".join(lines)
